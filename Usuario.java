public class Usuario {
    private String nome;
    private String email;
    private String senha;
    private String cpf;
    private String contato;

    Usuario (String nome, String email, String senha, String cpf , String contato) {
        this.nome = nome;
        this.email = email;
        this.senha = senha;
        this.cpf = cpf;
        this.contato = contato;
    }
}
